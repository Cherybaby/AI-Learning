
function y=XP_algorithm(a,Ctz)
% XP_algorithm:
% 供 fsolve 调用的约束方程函数。
% 输入:
%   a(1:3) - 姿态角参数，用于构造旋转矩阵
%   a(4:5) - 轮心平面坐标 (Ctx, Cty)
%   Ctz    - 当前工况的轮心目标 Z 坐标
% 输出:
%   y(1:5) - 五根连杆长度约束残差。理论收敛时应接近 0。

global A1 B1 A2 B2 A3 B3 A4 B4 A5 B5 C C1 LUP LLWR SCLP SCTR

% 由姿态角参数构造旋转矩阵分量。
% 与主脚本中的构造保持一致，用于将初始点位旋转到当前工况。
d11=cos(a(1))*cos(a(2));
d12=-sin(a(1))*cos(a(2));
d13=sin(a(2));
d21=sin(a(1))*cos(a(3))+cos(a(1))*sin(a(2))*sin(a(3));
d22=cos(a(1))*cos(a(3))-sin(a(1))*sin(a(2))*sin(a(3));
d23=-cos(a(2))*sin(a(3));
d31=sin(a(1))*sin(a(3))-cos(a(1))*sin(a(2))*cos(a(3));
d32=cos(a(1))*sin(a(3))+sin(a(1))*sin(a(2))*cos(a(3));
d33=cos(a(2))*cos(a(3));
E1=[d11,d12,d13;d21,d22,d23;d31,d32,d33];

% 计算平移向量 Y1，使变换后轮心 C 的坐标等于 [a(4), a(5), Ctz]。
% 也就是: E1*C + Y1 = [Ctx, Cty, Ctz]^T
Y1=[a(4)-(d11*C(1)+d12*C(2)+d13*C(3));a(5)-(d21*C(1)+d22*C(2)+d23*C(3));Ctz-(d31*C(1)+d32*C(2)+d33*C(3))];

% 齐次变换矩阵: 把初始硬点位置映射到当前姿态位置。
Dt=[E1,Y1;0,0,0,1];
B11=Dt*[B1,1]';
B22=Dt*[B2,1]';
B33=Dt*[B3,1]';
B44=Dt*[B4,1]';
B55=Dt*[B5,1]';

% 连杆长度约束残差:
% 当前工况长度 - 初始标称长度。
% fsolve 通过调节 a，使这 5 个残差同时逼近 0。
ss1=sqrt((B11(1)-A1(1))^2+(B11(2)-A1(2))^2+(B11(3)-A1(3))^2)-norm(B1-A1);
ss2=sqrt((B22(1)-A2(1))^2+(B22(2)-A2(2))^2+(B22(3)-A2(3))^2)-norm(B2-A2);
ss3=sqrt((B33(1)-A3(1))^2+(B33(2)-A3(2))^2+(B33(3)-A3(3))^2)-norm(B3-A3);
ss4=sqrt((B44(1)-A4(1))^2+(B44(2)-A4(2))^2+(B44(3)-A4(3))^2)-norm(B4-A4);
ss5=sqrt((B55(1)-A5(1))^2+(B55(2)-A5(2))^2+(B55(3)-A5(3))^2)-norm(B5-A5);

% 以列向量形式返回给 fsolve。
y=[ss1;ss2;ss3;ss4;ss5];
end

